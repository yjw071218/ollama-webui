import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'webui-storage-test-'));
process.env.WEBUI_DATA_DIR = directory;
process.env.WEBUI_DB_KEY = Buffer.alloc(32, 57).toString('base64');
const { database, closeDatabase, DB_FILE } = await import('../server/db.js');
const { applyChanges, changesSince, sweepTombstones } = await import('../server/records.js');
const { searchRecords } = await import('../server/recordSearch.js');
const { acknowledgeSync, syncFloor } = await import('../server/syncRetention.js');
const { readRevision } = await import('../server/recordHistory.js');
try {
  let db = database();
  db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run('alice','Alice',1);
  db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run('bob','Bob',1);
  const secret = '고유비밀문장_Secret98765';
  const put = (owner,id,text,stamp,since=0) => applyChanges(owner,{since, records:[{kind:'chat',id,updatedAt:stamp,payload:{title:'테스트',messages:[{role:'user',content:text}]}}]});
  put('alice','c',secret,1);
  assert.ok(!db.prepare("SELECT payload FROM records WHERE user_id='alice'").get().payload.includes(secret));
  assert.equal(changesSince('alice').records[0].payload.messages[0].content,secret);
  assert.equal(searchRecords('alice','비밀문장').hits[0].sessionId,'c');
  assert.equal(searchRecords('bob','비밀문장').hits.length,0);
  assert.equal(searchRecords('alice','비').hits.length,1);
  put('alice','c','수정된 내용',2);
  assert.equal(searchRecords('alice',secret).hits.length,0);
  assert.equal(searchRecords('alice','수정된').hits.length,1);
  assert.equal(readRevision('alice','chat','c',1).payload.messages[0].content,secret);
  assert.ok(!db.prepare('SELECT payload FROM record_history').get().payload.includes(secret));
  assert.ok(db.prepare('EXPLAIN QUERY PLAN SELECT id FROM record_search WHERE user_id=? AND token=?').all('alice','x').some(r=>/PRIMARY KEY|INDEX/.test(r.detail)));
  db.exec('PRAGMA wal_checkpoint(TRUNCATE)');
  assert.ok(!fs.readFileSync(DB_FILE).includes(Buffer.from(secret)));
  acknowledgeSync('alice','laptop',2); acknowledgeSync('alice','phone',2);
  applyChanges('alice',{since:2,records:[{kind:'chat',id:'c',updatedAt:3,deleted:true}]});
  acknowledgeSync('alice','laptop',3);
  assert.equal(sweepTombstones('alice',0),0,'phone has not seen deletion');
  acknowledgeSync('alice','phone',3);
  assert.equal(sweepTombstones('alice',0),1);
  assert.equal(syncFloor('alice'),3);
  assert.equal(put('alice','c',secret,4,2).resetRequired,true,'stale client cannot resurrect');
  assert.equal(changesSince('alice').records.length,0);
  assert.equal(put('alice','new','새 작업',5,3).applied,1);
  closeDatabase(); db=database();
  assert.equal(changesSince('alice').records[0].payload.messages[0].content,'새 작업');
  db.exec('DROP TRIGGER protect_records_UPDATE');
  db.prepare("UPDATE records SET payload=? WHERE user_id='alice'").run(JSON.stringify({title:secret,messages:[]}));
  db.exec("DELETE FROM meta WHERE key='storage-security-v1'");
  closeDatabase(); db=database();
  assert.equal(changesSince('alice').records[0].payload.title,secret,'legacy plaintext is migrated without losing content');
  assert.ok(!fs.readFileSync(DB_FILE).includes(Buffer.from(secret)),'migration scrubs old database pages');
  closeDatabase();
  process.env.WEBUI_DB_KEY=Buffer.alloc(32,58).toString('base64');
  assert.throws(()=>database(),/authenticate|Unsupported state/i);
  console.log('PASS encrypted disk/history, Unicode indexed search, account isolation, safe GC, stale upload rejection, restart, wrong key');
} finally {
  closeDatabase();
  if(path.dirname(path.resolve(directory))===path.resolve(os.tmpdir())) fs.rmSync(directory,{recursive:true,force:true});
}
